import {test} from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {spawn} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import {Store} from '../lib/store.mjs';
import {accountProfile} from '../lib/account-manager.mjs';
const root=path.dirname(path.dirname(fileURLToPath(import.meta.url)));
test('first-use starts empty and preserves added accounts and memories after reopening',t=>{
  const dir=fs.mkdtempSync(path.join(os.tmpdir(),'desk-onboarding-'));
  t.after(()=>fs.rmSync(dir,{recursive:true,force:true}));
  const store=new Store(dir,{empty:true});
  assert.equal(store.state.tasks.length,0);assert.equal(store.state.memories.length,0);
  for(const p of Object.values(store.state.accountManager.providers)){assert.deepEqual(p.accounts,[]);assert.equal(p.activeAccountId,null);assert.equal(p.autoSwitch,false);}
  store.state.accountManager.providers.antigravity.accounts.push(accountProfile('antigravity','我的账号','me@example.test'));
  store.addMemory('保持任务连续');
  const reopened=new Store(dir,{empty:true});
  assert.equal(reopened.state.memories[0].text,'保持任务连续');
  assert.equal(reopened.state.accountManager.providers.antigravity.accounts.length,1);
  assert.equal(reopened.state.accountManager.providers.antigravity.accounts[0].quota,null);
});
test('start page and workspace use an empty profile and do not auto-connect providers',async t=>{
  const dir=fs.mkdtempSync(path.join(os.tmpdir(),'desk-start-http-'));
  const port=22317+Math.floor(Math.random()*1000),origin=`http://127.0.0.1:${port}`;
  const child=spawn(process.execPath,[path.join(root,'server.mjs')],{env:{...process.env,AGENT_DESK_EDITION:'commercial',PORT:String(port),AGENT_DESK_DATA:dir,AGENT_DESK_SEED_DEMO:'0'},windowsHide:true,stdio:['ignore','pipe','pipe']});
  t.after(async()=>{if(child.exitCode==null){const ended=new Promise(r=>child.once('exit',r));child.kill();await ended;}fs.rmSync(dir,{recursive:true,force:true});});
  await new Promise((resolve,reject)=>{child.stdout.once('data',resolve);child.once('error',reject);child.once('exit',code=>reject(new Error('server exit '+code)));});
  const landing=await fetch(origin),cookie=landing.headers.get('set-cookie').split(';')[0];
  assert.match(await landing.text(),/选择平台后继续/);
  const workspace=await fetch(origin+'/workspace?agent=antigravity&setup=1');assert.equal(workspace.status,200);assert.match(await workspace.text(),/account-dialog/);
  const state=await(await fetch(origin+'/api/state',{headers:{Cookie:cookie}})).json();
  const bridgeDenied=await fetch(origin+'/internal/delegate',{method:'POST',headers:{Cookie:cookie,Origin:origin,'Content-Type':'application/json'},body:JSON.stringify({clientId:'forged',args:{requestId:'test',prompt:'untrusted'}})});
  assert.equal(bridgeDenied.status,403);assert.doesNotMatch(JSON.stringify(state),/AGENT_DESK_PLATFORM_TOKEN|platformClientId/);
  assert.equal(state.tasks.length,0);assert.equal(state.memories.length,0);
  assert.equal(state.accountManager.providers.codex.accounts.length,0);assert.equal(state.accountManager.providers.antigravity.accounts.length,0);
  assert.equal(state.runtime.codex.connected,false);assert.equal(state.runtime.antigravity.connected,false);
  const denied=await fetch(origin+'/api/accounts/task',{method:'POST',headers:{Cookie:cookie,Origin:origin,'X-Agent-Desk':'1','Content-Type':'application/json'},body:JSON.stringify({provider:'codex',goal:'不能在未添加账号前执行'})});
  assert.equal(denied.status,400);assert.match((await denied.json()).error,/先添加账号/);
  const validation=await fetch(origin+'/api/validation/quota',{method:'POST',headers:{Cookie:cookie,Origin:origin,'X-Agent-Desk':'1','Content-Type':'application/json'},body:'{}'});assert.equal(validation.status,404);
  const headers={Cookie:cookie,Origin:origin,'X-Agent-Desk':'1','Content-Type':'application/json'};
  const create=body=>fetch(origin+'/api/task',{method:'POST',headers,body:JSON.stringify(body)});
  const invalid=await create({goal:'invalid',mode:'live',executionMode:'workspace',networkAccess:'true'});
  assert.equal(invalid.status,400);
  const online=await create({goal:'isolated permission test',mode:'live',executionMode:'workspace',networkAccess:true});
  assert.equal(online.status,200);const {taskId}=await online.json();
  const after=await(await fetch(origin+'/api/state',{headers:{Cookie:cookie}})).json();
  const task=after.tasks.find(t=>t.id===taskId);assert.equal(task.executionMode,'workspace');assert.equal(task.networkAccess,true);
  const persisted=JSON.parse(fs.readFileSync(path.join(dir,'state.json'),'utf8')).tasks.find(t=>t.id===taskId);
  assert.equal(persisted.networkAccess,true);
  const exported=await(await fetch(origin+'/api/context?taskId='+taskId,{headers:{Cookie:cookie}})).json();
  assert.equal(exported.taskId,taskId);assert.equal(exported.networkAccess,true);
  const readonly=await create({goal:'readonly does not grant network',mode:'live',executionMode:'read-only',networkAccess:true});
  assert.equal(readonly.status,200);
  const finalState=await(await fetch(origin+'/api/state',{headers:{Cookie:cookie}})).json();
  assert.equal(finalState.tasks.find(t=>t.id===(JSON.parse(fs.readFileSync(path.join(dir,'state.json'),'utf8')).selectedTaskId)).networkAccess,false);
});
